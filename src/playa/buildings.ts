export const BUILD_TIMES = [900, 1895, 3960, 8460, 18000, 28800, 41100, 66420, 144000, 313200, 691200, 1152000, 1728000, 2221200, 2880000, 3801600, 4147200, 4492800, 4838400, 5184000]

function ceilTo(value: number, step: number) {
  return Math.ceil(value / step) * step
}

export function buildTime(level: number, quarters: number, underworld = false) {
  const multiplier = 1 - 0.05 * quarters

  if (underworld ? level > 15 : level > 20) {
    return 51840 * multiplier * 100 * 1000
  }

  const time = BUILD_TIMES[level - 1]

  return ceilTo(time * multiplier, time > 3600 ? 100 : 1) * 1000
}

export function gemTime(duration: number, quarters: number) {
  return duration * (1 - quarters * 0.05)
}
